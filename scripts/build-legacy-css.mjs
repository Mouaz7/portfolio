// Builds public/legacy.css: the site's layered Tailwind CSS without @layer.
//
// Browsers older than iOS/Safari 15.4 and Chrome 99 do not understand cascade
// layers and drop every @layer block, which removes Tailwind's reset, theme
// variables and all utility classes. The inline legacy script (see
// lib/security/inline-scripts.cjs) loads this file only in those browsers, as
// the first stylesheet, so the site's own unlayered CSS still comes later and
// wins exactly as layers would make it win. Modern browsers never request it.
//
// Runs as "prebuild"; the output is generated and git-ignored.
import { createRequire } from "node:module";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const require = createRequire(import.meta.url);
const viewportFallback = require("../postcss/viewport-fallback.cjs");
const colorMixFallback = require("../postcss/color-mix-fallback.cjs");

const root = fileURLToPath(new URL("..", import.meta.url));
const input = path.join(root, "app/global.css");
const output = path.join(root, "public/legacy.css");
// Browsers order Tailwind's layers slightly differently (the base import is
// declared first), but theme and properties only define custom properties and
// components is empty, so this order gives the same result.
const LAYER_ORDER = ["theme", "base", "components", "utilities"];

// Pseudo-elements that older engines do not know. One unknown selector makes
// the whole rule invalid there, so they are split off into their own rules.
const RISKY_PSEUDO = /::(?:backdrop|file-selector-button)\b/;

function splitRiskySelectors(root) {
  root.walkRules((rule) => {
    const risky = rule.selectors.filter((selector) => RISKY_PSEUDO.test(selector));
    if (risky.length === 0 || risky.length === rule.selectors.length) return;
    rule.selectors = rule.selectors.filter((selector) => !RISKY_PSEUDO.test(selector));
    for (const selector of risky.reverse()) rule.after(rule.clone({ selectors: [selector] }));
  });
}

/** Moves the content of every @layer block out, in cascade-layer order. */
function flattenLayers(css) {
  const parsed = postcss.parse(css);
  const byLayer = new Map(LAYER_ORDER.map((name) => [name, []]));
  parsed.walkAtRules("layer", (rule) => {
    if (!rule.nodes) {
      rule.remove(); // "@layer a, b;" order statement
      return;
    }
    const name = rule.params.trim();
    if (!byLayer.has(name)) byLayer.set(name, []);
    byLayer.get(name).push(...rule.nodes.map((node) => node.clone()));
    rule.remove();
  });
  // Unlayered rules from global.css are already in the normal stylesheet;
  // only the layered content is needed here.
  const flat = postcss.root();
  for (const nodes of byLayer.values()) flat.append(...nodes);
  splitRiskySelectors(flat);
  return flat.toString();
}

const source = await readFile(input, "utf8");
const compiled = await postcss([tailwind({ base: root, optimize: { minify: false } })]).process(source, { from: input });
const flattened = flattenLayers(compiled.css);
const withFallbacks = await postcss([viewportFallback, colorMixFallback]).process(flattened, {
  from: undefined,
});
await mkdir(path.dirname(output), { recursive: true });
await writeFile(
  output,
  `/* Generated by scripts/build-legacy-css.mjs. Loaded only by browsers without cascade layers. */\n${withFallbacks.css}`,
);
console.log(`legacy.css: ${Math.round(withFallbacks.css.length / 1024)} KB`);
